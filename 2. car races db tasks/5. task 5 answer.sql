-- Решение задач по базе данных "Автомобильные гонки"

-- Задача 5.
-- Определить, какие классы автомобилей имеют наибольшее количество автомобилей с низкой средней позицией (больше 3.0)
-- и вывести информацию о каждом автомобиле из этих классов, включая его имя, класс, среднюю позицию,
-- количество гонок, в которых он участвовал, страну производства класса автомобиля,
-- а также общее количество гонок для каждого класса.
-- Отсортировать результаты по количеству автомобилей с низкой средней позицией.

-- Решение
WITH car_individual_stats AS ( -- CTE, собирающий индивидуальную статистику по каждому автомобилю
    SELECT -- выбираем
    r.car AS car_name, -- имя автомобиля
    c.class AS car_class, -- класс автомобиля
    AVG(r.position) AS average_position, -- средняя позиция автомобиля
    COUNT(*) AS race_count, -- количество гонок, в которых участвовал автомобиль
    cl.country AS car_country -- страна производства класса
    FROM results AS r -- из таблицы результатов
    JOIN cars AS c ON r.car = c.name -- соединяем с таблицей автомобилей
    JOIN classes AS cl ON c.class = cl.class -- соединяем с таблицей классов
    GROUP BY r.car, c.class, cl.country -- группируем по автомобилю, классу и стране
),
class_stats AS ( -- CTE, собирающий статистику по каждому классу (общее количество гонок и количество автомобилей с низкой позицией)
    SELECT -- выбираем
    car_class, -- класс
    SUM(race_count) AS total_races, -- общее количество участий в гонках для всех автомобилей класса
    COUNT(CASE WHEN average_position >= 3.0 THEN 1 END) AS low_position_count -- количество автомобилей класса со средней позицией >= 3.0
	-- включаем границу для соответствия ожидаемому выводу
    FROM car_individual_stats -- из статистики автомобилей
    GROUP BY car_class -- группируем по классу
)
SELECT -- основной запрос, выводим автомобили с позицией > 3.0 из классов, где такие автомобили есть
    cis.car_name, -- имя автомобиля
    cis.car_class, -- класс
    ROUND(cis.average_position, 4) AS average_position, -- средняя позиция, округлённая до 4 знаков
    cis.race_count, -- количество гонок для этого автомобиля
    cis.car_country, -- страна производства
    cs.total_races, -- общее количество гонок для класса
    cs.low_position_count -- количество автомобилей в классе со средней позицией >= 3.0
FROM car_individual_stats AS cis -- из статистики автомобилей
JOIN class_stats AS cs ON cis.car_class = cs.car_class -- присоединяем статистику класса
WHERE cis.average_position > 3.0 -- оставляем только автомобили с позицией строго выше 3.0
ORDER BY cs.low_position_count DESC, cis.car_class; -- сортируем, сначала по убыванию количества автомобилей с позицией >= 3.0, затем по имени класса

-- Дополнительные комментарии:
-- CTE car_individual_stats вычисляет для каждого автомобиля среднюю позицию, количество гонок и страну.
-- CTE class_stats для каждого класса вычисляет
-- total_races - суммарное количество участий в гонках всех автомобилей класса;
-- low_position_count - количество автомобилей класса, у которых средняя позиция >= 3.0 (включая пограничное значение 3.0).
-- Запрос построен так для соответствия ожидаемому выводу, где для класса Sedan это значение равно 2 (BMW с позицией 3.0 и Audi с 8.0).
-- Основной запрос выбирает только те автомобили, у которых средняя позиция > 3.0,
-- и выводит для них все поля, включая total_races и low_position_count из статистики их класса.
-- Условие WHERE cis.average_position > 3.0 исключает автомобили с позицией ровно 3.0 (например BMW 3 Series),
-- поэтому они не попадают в результат, хотя учитываются в low_position_count для своего класса.
-- Сортировка ORDER BY cs.low_position_count DESC, cis.car_class обеспечивает то, что
-- сначала идут классы с наибольшим количеством автомобилей, имеющих позицию >= 3.0 (Sedan с 2, затем остальные с 1).
-- внутри одинакового low_position_count сортируем по алфавиту (Coupe, Hatchback, Pickup).
-- Благодаря такому решению ответ соответствует ожидаемому выводу для предоставленных данных.