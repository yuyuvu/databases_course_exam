-- Решение задач по базе данных "Бронирование отелей"

-- Задача 3.
-- Определите категорию каждого отеля на основе средней стоимости номера:
-- дешевый при средней стоимости < 175 долларов.
-- средний при средней стоимости от 175 до 300 долларов.
-- дорогой при средней стоимости > 300 долларов.
-- Для каждого клиента определить предпочитаемый тип отеля.
-- Если есть хотя бы один дорогой, тогда дорогой,
-- иначе если есть хотя бы один средний, тогда средний, иначе дешевый.
-- Вывести ID_customer, name, preferred_hotel_type, visited_hotels (список уникальных посещённых отелей через запятую).
-- Отсортировать по принципу сначала дешевые, затем средние, затем дорогие.

-- Решение
WITH hotel_category AS ( -- CTE, собирающий категории отелей на основе средней цены номеров
    SELECT -- выбираем
    h.ID_hotel, -- идентификатор отеля
    h.name AS hotel_name, -- название отеля
        CASE -- определяем категорию
        WHEN AVG(r.price) < 175 THEN 'Дешевый'
        WHEN AVG(r.price) BETWEEN 175 AND 300 THEN 'Средний'
        ELSE 'Дорогой'
        END AS hotel_type -- тип отеля
    FROM hotel AS h -- из таблицы отелей
    JOIN room AS r ON h.ID_hotel = r.ID_hotel -- соединяем с номерами по идентификатору отеля
    GROUP BY h.ID_hotel, h.name -- группируем по отелю
),
customer_hotels AS ( -- CTE, собирающий для каждого клиента посещённые отели и их типы
    SELECT -- выбираем
    c.ID_customer, -- идентификатор клиента
    c.name, -- имя клиента
    hc.hotel_name, -- название отеля
    hc.hotel_type -- тип отеля
    FROM customer AS c -- из таблицы клиентов
    JOIN booking AS b ON c.ID_customer = b.ID_customer -- соединяем с бронированиями по клиенту
    JOIN room AS r ON b.ID_room = r.ID_room -- соединяем с номерами по бронированию
    JOIN hotel_category AS hc ON r.ID_hotel = hc.ID_hotel -- соединяем с категориями отелей по идентификатору отеля
),
customer_pref AS ( -- CTE, собирающий предпочитаемый тип отеля и список отелей для каждого клиента
    SELECT -- выбираем
    ID_customer, -- идентификатор клиента
    name, -- имя клиента
    STRING_AGG(DISTINCT hotel_name, ', ' ORDER BY hotel_name) AS visited_hotels, -- список уникальных отелей через запятую с пробелом, отсортированный по названию
    MAX(CASE hotel_type -- максимальный приоритет среди типов отелей клиента
        WHEN 'Дешевый' THEN 1
        WHEN 'Средний' THEN 2
        WHEN 'Дорогой' THEN 3
        END) AS priority -- 1 - дешевый, 2 - средний, 3 - дорогой
    FROM customer_hotels -- из предыдущего CTE
    GROUP BY ID_customer, name -- группируем по клиенту
)

SELECT -- основной запрос, выводим информацию о клиентах
    cp.ID_customer, -- идентификатор клиента
    cp.name, -- имя клиента
    CASE cp.priority -- преобразуем числовой приоритет в текстовый тип отеля
    WHEN 1 THEN 'Дешевый'
    WHEN 2 THEN 'Средний'
    WHEN 3 THEN 'Дорогой'
    END AS preferred_hotel_type, -- предпочитаемый тип отеля
    cp.visited_hotels -- список посещённых отелей
FROM customer_pref AS cp -- из CTE
ORDER BY cp.priority, cp.ID_customer; -- сортируем сначала по приоритету, затем по идентификатору клиента

-- Дополнительные комментарии:
-- CTE hotel_category вычисляет для каждого отеля среднюю цену номера (AVG(r.price)) и присваивает категорию по условиям.
-- CTE customer_hotels собирает для каждого клиента все пары (название отеля, тип отеля) через цепочку JOIN.
-- CTE customer_pref для каждого клиента формирует список уникальных отелей с помощью STRING_AGG(DISTINCT ORDER BY),
-- вычисляет максимальный числовой приоритет среди типов отелей (дорогой = 3, средний = 2, дешевый = 1).
-- Реализуется правило, что если есть дорогой отель, тогда priority = 3, иначе если есть средний, тогда priority = 2, иначе priority = 1.
-- Основной запрос преобразует priority обратно в текст и выводит результат.
-- Числовой приоритет нужен, чтобы итог можно было сортировать в нужном порядке.
-- ORDER BY cp.priority, cp.ID_customer обеспечивает порядок, согласно которому сначала идут клиенты с дешёвыми отелями, затем со средними, затем с дорогими.
-- Внутри каждой группы клиенты упорядочены по ID_customer для соответствия ожидаемому выводу.