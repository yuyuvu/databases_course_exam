-- Решение задач по базе данных "Автомобильные гонки"

-- Задача 2.
-- Определить автомобиль, который имеет наименьшую среднюю позицию в гонках среди всех автомобилей,
-- и вывести информацию об этом автомобиле, включая его класс, среднюю позицию, количество гонок,
-- в которых он участвовал, и страну производства класса автомобиля.
-- Если несколько автомобилей имеют одинаковую наименьшую среднюю позицию, выбрать один из них
-- по алфавиту (по имени автомобиля).

-- Решение
-- Чтобы итоговый запрос был один, используем CTE (Common Table Expression), то есть временные именованные результаты запросов.
WITH car_avg_position_and_count AS ( -- первый CTE, собирающий статистику по каждому автомобилю
    SELECT -- выбираем данные
    r.car AS car_name, -- имя автомобиля
    c.class AS car_class, -- класс автомобиля
    AVG(r.position) AS average_position, -- средняя позиция в гонках
    COUNT(*) AS race_count -- количество гонок, в которых участвовал
    FROM results AS r -- из таблицы результатов
    JOIN cars AS c ON r.car = c.name -- соединяем с таблицей автомобилей по имени
    GROUP BY r.car, c.class -- группируем по автомобилю и классу
),
min_average AS ( -- второй CTE, собирающий наименьшую среднюю позиция среди всех автомобилей
    SELECT -- выбираем
    MIN(average_position) AS best_avg_position -- минимальное значение средней позиции
    FROM car_avg_position_and_count -- из первого CTE
)

SELECT -- основной запрос, выбираем лучший автомобиль
capc.car_name, -- имя автомобиля
capc.car_class, -- класс
ROUND(capc.average_position, 4) AS average_position, -- средняя позиция, округлённая до 4 знаков после запятой
capc.race_count, -- количество гонок
cl.country AS car_country -- страна производства из таблицы классов
FROM car_avg_position_and_count AS capc -- из первого CTE
JOIN min_average AS ma ON capc.average_position = ma.best_avg_position -- только автомобили с минимальной средней позицией
JOIN classes AS cl ON capc.car_class = cl.class -- соединяем с классами, чтобы получить страну
ORDER BY capc.car_name -- сортируем по имени автомобиля по алфавиту
LIMIT 1; -- берём первую по алфавиту при совпадении средней позиции

-- Дополнительные комментарии:
-- CTE car_avg_position_and_count вычисляет для каждого автомобиля среднюю позицию и количество гонок.
-- CTE min_average находит наименьшую среднюю позицию среди всех автомобилей.
-- Основной запрос соединяет car_avg_position_and_count с min_average, оставляя только автомобили,
-- имеющие минимальную среднюю позицию.
-- Присоединяем classes, чтобы получить страну как car_country.
-- ORDER BY capc.car_name сортирует по алфавиту, LIMIT 1 оставляет первый автомобиль.
-- В данных, исходя из ответа на предыдущую задачу, минимальная средняя позиция = 1.0000 у Ferrari 488 и Ford Mustang.
-- По алфавиту Ferrari 488 идёт раньше, чем Ford Mustang, поэтому должен быть выбран Ferrari.
-- ROUND(cs.average_position, 4) обеспечивает формат 1.0000, как в ожидаемом выводе.