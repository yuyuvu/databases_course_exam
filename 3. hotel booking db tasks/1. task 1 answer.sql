-- Решение задач по базе данных "Бронирование отелей"

-- Задача 1.
-- Определить, какие клиенты сделали более двух бронирований в разных отелях,
-- и вывести информацию о каждом таком клиенте, включая его имя, электронную почту, телефон,
-- общее количество бронирований, а также список отелей, в которых они бронировали номера
-- (объединенные в одно поле через запятую). Также подсчитать среднюю длительность их пребывания
-- (в днях) по всем бронированиям. Отсортировать результаты по количеству бронирований в порядке убывания.

-- Решение
WITH customer_bookings AS ( -- CTE, агрегирующий данные по каждому клиенту
    SELECT -- выбираем
    c.ID_customer, -- идентификатор клиента
    c.name, -- имя клиента
    c.email, -- электронная почта
    c.phone, -- телефон
    COUNT(b.ID_booking) AS total_bookings, -- общее количество бронирований
    COUNT(DISTINCT h.ID_hotel) AS distinct_hotels, -- количество различных отелей
    STRING_AGG(DISTINCT h.name, ', ' ORDER BY h.name) AS hotel_list, -- список отелей через запятую без повторений и отсортированный
    AVG(b.check_out_date - b.check_in_date) AS avg_stay_days -- средняя длительность пребывания в днях
    FROM customer AS c -- из таблицы клиентов
    JOIN booking AS b ON c.ID_customer = b.ID_customer -- соединяем с бронированиями
    JOIN room AS r ON b.ID_room = r.ID_room -- соединяем с номерами
    JOIN hotel AS h ON r.ID_hotel = h.ID_hotel -- соединяем с отелями
    GROUP BY c.ID_customer, c.name, c.email, c.phone -- группируем по клиенту
    HAVING COUNT(b.ID_booking) > 2 -- оставляем клиентов с более чем двумя бронированиями
    AND COUNT(DISTINCT h.ID_hotel) > 1 -- и бронировавших в разных отелях, минимум два различных отеля
)
SELECT -- основной запрос, выводим нужные поля
    cb.name, -- имя клиента
    cb.email, -- электронная почта
    cb.phone, -- телефон
    cb.total_bookings, -- общее количество бронирований
    cb.hotel_list, -- список отелей через запятую
    ROUND(cb.avg_stay_days, 4) AS avg_stay_days -- средняя длительность, округлённая до 4 знаков
FROM customer_bookings AS cb -- из CTE
ORDER BY cb.total_bookings DESC; -- сортируем по количеству бронирований по убыванию

-- Дополнительные комментарии:
-- CTE customer_bookings собирает для каждого клиента количество бронирований, количество различных отелей,
-- список уникальных отелей через STRING_AGG с DISTINCT и с сортировкой по имени, а также среднюю длительность пребывания.
-- Средняя длительность вычисляется как среднее арифметическое разницы между датой выезда и датой заезда.
-- HAVING фильтрует группы total_bookings > 2 (более двух бронирований) и distinct_hotels > 1 (разные отели).
-- STRING_AGG(DISTINCT ) гарантирует, что каждый отель упоминается в списке только один раз, даже если клиент бронировал в нём номера несколько раз.
-- ROUND(avg_stay_days, 4) приводит результат к формату с четырьмя десятичными знаками, как в ожидаемом выводе.
-- Сортировка ORDER BY total_bookings DESC выводит клиентов с наибольшим числом бронирований первыми.