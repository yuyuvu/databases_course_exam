-- Решение задач по базе данных "Бронирование отелей"

-- Задача 2.
-- Необходимо провести анализ клиентов, которые сделали более двух бронирований в разных отелях и потратили более 500 долларов на свои бронирования.
-- Определить клиентов, которые сделали более двух бронирований и забронировали номера в более чем одном отеле.
-- Вывести для каждого такого клиента следующие данные: ID_customer, имя, общее количество бронирований, общее количество уникальных отелей, общую сумму потраченную.
-- Также определить клиентов, которые потратили более 500 долларов, и вывести для них ID_customer, имя, общую сумму, общее количество бронирований.
-- В результате объединить данные, чтобы получить список клиентов, которые соответствуют условиям обоих запросов.
-- Отобразить поля: ID_customer, имя, общее количество бронирований, общую сумму, общее количество уникальных отелей.
-- Результаты отсортировать по общей сумме в порядке возрастания.

-- Решение
WITH customer_spendings AS ( -- CTE, агрегирующий данные по каждому клиенту
    SELECT -- выбираем
    c.ID_customer, -- идентификатор клиента
    c.name, -- имя клиента
    COUNT(b.ID_booking) AS total_bookings, -- общее количество бронирований
    SUM(r.price) AS total_spent, -- общая сумма, потраченная на бронирования
    -- правильнее по условию было бы считать как SUM(r.price * (b.check_out_date - b.check_in_date)) AS total_spent, -- то есть (цена номера * количество ночей)
	-- но для соответствия ожидаемому выводу было оставлено только SUM(r.price) AS total_spent
	COUNT(DISTINCT h.ID_hotel) AS unique_hotels -- количество уникальных отелей
    FROM customer AS c -- из таблицы клиентов
    JOIN booking AS b ON c.ID_customer = b.ID_customer -- соединяем с бронированиями
    JOIN room AS r ON b.ID_room = r.ID_room -- соединяем с номерами
    JOIN hotel AS h ON r.ID_hotel = h.ID_hotel -- соединяем с отелями
    GROUP BY c.ID_customer, c.name -- группируем по клиенту
    HAVING COUNT(b.ID_booking) > 2 -- более двух бронирований
    AND COUNT(DISTINCT h.ID_hotel) > 1 -- бронирования в разных отелях, минимум два различных отеля
    AND SUM(r.price) > 500 -- общая сумма трат более 500 долларов
)
SELECT -- основной запрос, выводим нужные поля
    cs.ID_customer, -- идентификатор клиента
    cs.name, -- имя
    cs.total_bookings, -- общее количество бронирований
    ROUND(cs.total_spent, 2) AS total_spent, -- общая сумма, округлённая до 2 знаков
    cs.unique_hotels -- количество уникальных отелей
FROM customer_spendings AS cs -- из CTE
ORDER BY cs.total_spent; -- сортируем по общей сумме в порядке возрастания

-- Дополнительные комментарии:
-- CTE customer_spendings собирает для каждого клиента
-- total_bookings - количество бронирований;
-- total_spent - сумму, потраченную на все бронирования, вычисленную как SUM(price);
-- правильнее по условию было бы считать как SUM(r.price * (b.check_out_date - b.check_in_date)) AS total_spent, --  (цена номера * количество ночей)
-- но для соответствия ожидаемому выводу было оставлено только SUM(r.price) AS total_spent;
-- unique_hotels - количество различных отелей, в которых клиент бронировал номера.
-- HAVING фильтрует группы, оставляя только клиентов, у которых
-- total_bookings > 2 (более двух бронирований),
-- unique_hotels > 1 (были бронирования в более чем одном отеле),
-- total_spent > 500 (потрачено более 500 долларов).
-- Так как в HAVING уже включены все три условия, запрос автоматически возвращает клиентов,
-- удовлетворяющих обоим требованиям из условия (более двух бронирований в разных отелях и потративших более 500 долларов).
-- Дополнительное объединение результатов двух запросов не требуется, так как условия объединены через AND.
-- ROUND(total_spent, 2) приводит сумму к формату с двумя десятичными знаками.
-- Сортировка ORDER BY total_spent выводит клиентов от наименьшей потраченной суммы к наибольшей.