-- Решение задач по базе данных "транспортные средства"

-- Задача 2.
-- Найти информацию о производителях и моделях различных типов транспортных средств
-- (автомобили, мотоциклы и велосипеды), которые соответствуют заданным критериям.
-- У автомобилей мощность > 150 лошадиных сил, объем < 3 л, цена < 35000.
-- У мотоциклов мощность > 150 лошадиных сил, объем < 1.5 л, цена < 20000.
-- У велосипедов передач > 18, цена < 4000. Мощность и объем должны быть отражены как NULL.
-- Результаты должны быть объединены в один набор данных и отсортированы по мощности в порядке убывания. 
-- Для велосипедов, у которых нет значения мощности (NULL), они будут располагаться внизу списка.
-- В выводе должны быть указаны производитель (maker), номер модели (model), мощность (horsepower), 
-- объем двигателя (engine_capacity) и тип транспортного средства.

-- Решение
SELECT
v.maker, -- берём данные из столбца производитель (maker)
c.model, -- берём данные из столбца номер модели (model)
c.horsepower, -- берём данные из столбца мощность (horsepower)
c.engine_capacity, -- берём данные из столбца объем двигателя (engine_capacity)
v.type AS vehicle_type -- берём данные из столбца тип транспортного средства
FROM car as c -- из таблицы car
JOIN vehicle as v ON c.model = v.model -- соединяем данные таблиц vehicle и car по данным стобца model через inner join
WHERE c.horsepower > 150 AND c.engine_capacity < 3.0 AND c.price < 35000.00 -- берём строки, где мощность > 150 лошадиных сил, объем < 3 л, цена < 35000

UNION ALL -- объединяем результат запроса с результатом другого запроса

SELECT
v.maker, -- берём данные из столбца производитель (maker)
m.model, -- берём данные из столбца номер модели (model)
m.horsepower, -- берём данные из столбца мощность (horsepower)
m.engine_capacity, -- берём данные из столбца объем двигателя (engine_capacity)
v.type AS vehicle_type -- берём данные из столбца тип транспортного средства
FROM motorcycle as m -- из таблицы motorcycle
JOIN vehicle as v ON m.model = v.model -- соединяем данные таблиц vehicle и motorcycle по данным стобца model через inner join
WHERE m.horsepower > 150 AND m.engine_capacity < 1.5 AND m.price < 20000.00 -- берём строки, где мощность > 150 лошадиных сил, объем < 1.5 л, цена < 20000

UNION ALL -- объединяем результат запроса с результатом другого запроса

SELECT
v.maker, -- берём данные из столбца производитель (maker)
b.model, -- берём данные из столбца номер модели (model)
NULL AS horsepower, -- мощность должны быть равна NULL
NULL AS engine_capacity, -- объем должен быть равен NULL
v.type AS vehicle_type -- берём данные из столбца тип транспортного средства
FROM bicycle as b -- из таблицы bicycle
JOIN vehicle as v ON b.model = v.model -- соединяем данные таблиц vehicle и bicycle по данным стобца model через inner join
WHERE b.gear_count > 18 AND b.price < 4000.00 -- берём строки, где передач > 18, цена < 4000

ORDER BY horsepower DESC NULLS LAST; -- сортируем по убыванию мощности; строки с мощностью, равной NULL, размещаем в конце результата

-- Дополнительные комментарии:
-- Используем UNION ALL для объединения результатов в один набор данных.
-- Для велосипедов явно указываем NULL для horsepower и engine_capacity,
-- чтобы структура результата совпадала с первыми двумя результатами.
-- Благодаря ORDER BY horsepower DESC NULLS LAST автомобили и мотоциклы будут отсортированы по убыванию мощности,
-- а велосипеды с NULL будут размещены внизу результата.