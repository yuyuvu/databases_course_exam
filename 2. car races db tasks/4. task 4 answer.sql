-- Решение задач по базе данных "Автомобильные гонки"

-- Задача 4.
-- Определить, какие автомобили имеют среднюю позицию лучше (меньше) средней позиции всех автомобилей в своем классе
-- (то есть автомобилей в классе должно быть минимум два, чтобы выбрать один из них).
-- Вывести информацию об этих автомобилях, включая их имя, класс, среднюю позицию, количество гонок,
-- в которых они участвовали, и страну производства класса автомобиля.
-- Отсортировать результаты по классу и затем по средней позиции в порядке возрастания.

-- Решение
WITH car_individual_stats AS ( -- CTE, собирающий индивидуальную статистику по каждому автомобилю
    SELECT -- выбираем
    r.car AS car_name, -- имя автомобиля
    c.class AS car_class, -- класс автомобиля
    AVG(r.position) AS average_position, -- средняя позиция автомобиля во всех гонках
    COUNT(*) AS race_count, -- количество гонок, в которых участвовал автомобиль
    cl.country AS car_country -- страна производства класса
    FROM results AS r -- из таблицы результатов
    JOIN cars AS c ON r.car = c.name -- соединяем с таблицей автомобилей
    JOIN classes AS cl ON c.class = cl.class -- соединяем с таблицей классов для страны
    GROUP BY r.car, c.class, cl.country -- группируем по автомобилю, классу и стране
),
class_avg_stats AS ( -- CTE, собирающий среднюю позицию среди всех автомобилей по каждому классу
    SELECT -- выбираем
    c.class AS car_class, -- класс
    AVG(r.position) AS class_avg_position, -- среднюю позицию по классу
    COUNT(DISTINCT c.name) AS car_count -- количество автомобилей в классе
    FROM cars AS c -- из таблицы автомобилей
    JOIN results AS r ON c.name = r.car -- соединяем с результатами
    GROUP BY c.class -- группируем по классу
    HAVING COUNT(DISTINCT c.name) >= 2 -- оставляем только классы с минимум двумя автомобилями
)
SELECT -- основной запрос, отбираем автомобили, у которых средняя позиция лучше средней по классу
    cis.car_name, -- имя автомобиля
    cis.car_class, -- класс
    ROUND(cis.average_position, 4) AS average_position, -- средняя позиция, округлённая до 4 знаков
    cis.race_count, -- количество гонок
    cis.car_country -- страна производства
FROM car_individual_stats AS cis -- из статистики автомобилей
JOIN class_avg_stats AS cas ON cis.car_class = cas.car_class -- соединяем с классовой статистикой
WHERE cis.average_position < cas.class_avg_position -- оставляем строки, где средняя позиция автомобиля лучше (меньше) средней по классу
ORDER BY cis.car_class, cis.average_position; -- сортируем по классу, затем по средней позиции по возрастанию

-- Дополнительные комментарии:
-- CTE car_individual_stats вычисляет для каждого автомобиля его среднюю позицию, количество гонок и страну.
-- CTE class_avg_stats вычисляет для каждого класса среднюю позицию по всем автомобилям этого класса
-- и количество автомобилей в классе. HAVING COUNT(DISTINCT c.name) >= 2 оставляет только классы с двумя и более автомобилями.
-- Основной запрос соединяет две CTE по классу и отбирает только те автомобили, чья личная средняя позиция
-- строго меньше средней по их классу, то есть лучше.
-- Сортировка ORDER BY cis.car_class, cis.average_position сортирует результаты сначала по алфавиту по названиям классов,
-- внутри каждого класса сортирует по возрастанию средней позиции (от лучшей к худшей).
-- На основе данных подходят классы Sedan (BMW 3 Series, средняя 3.0 < 5.5) и SUV (Toyota RAV4, средняя 2.0 < 2.5).
-- Остальные классы содержат только один автомобиль и исключаются условием HAVING.
-- ROUND приводит значения средней позиции к формату с 4 знаками после запятой.